class TestPolicyEvaluator:
    """The policy parser is the core decision logic shared with real CP-ABE."""

    def test_single_attribute(self):
        assert policy_satisfied("role_Analyst", ["role_Analyst"])
        assert not policy_satisfied("role_Analyst", ["role_Executor"])

    def test_and(self):
        p = "clearance_2 and task_incident-1"
        assert policy_satisfied(p, ["clearance_2", "task_incident-1"])
        assert not policy_satisfied(p, ["clearance_2"])

    def test_or(self):
        p = "clearance_2 or clearance_3"
        assert policy_satisfied(p, ["clearance_2"])
        assert policy_satisfied(p, ["clearance_3"])
        assert not policy_satisfied(p, ["clearance_1"])

    def test_nested(self):
        p = "role_Planner and (clearance_2 or clearance_3)"
        assert policy_satisfied(p, ["role_Planner", "clearance_2"])
        assert policy_satisfied(p, ["role_Planner", "clearance_3"])
        assert not policy_satisfied(p, ["role_Planner", "clearance_1"])
        assert not policy_satisfied(p, ["clearance_3"])  # missing role

    def test_realistic_policy_from_labels(self):
        """Simulate a policy generated by policy_from_label()."""
        # D-layer: owner, descendants, auditor can read
        p = "agent_planner-1 or descendantof_planner-1 or role_Auditor"
        assert policy_satisfied(p, ["agent_planner-1"])
        assert policy_satisfied(p, ["descendantof_planner-1"])
        assert policy_satisfied(p, ["role_Auditor"])
        assert not policy_satisfied(p, ["agent_analyst-2"])

    def test_clearance_chain(self):
        """clearance_i is satisfied if i >= required level."""
        p = "(clearance_1 or clearance_2 or clearance_3)"
        assert policy_satisfied(p, ["clearance_2"])
        assert policy_satisfied(p, ["clearance_3"])
        assert not policy_satisfied(p, ["clearance_0"])

    def test_complex_compound(self):
        p = ("(clearance_2 or clearance_3) and task_t1 "
             "and (group_sec or group_ops) and epoch_1")
        attrs = ["clearance_2", "task_t1", "group_sec", "epoch_1"]
        assert policy_satisfied(p, attrs)

        # Missing group
        attrs_bad = ["clearance_2", "task_t1", "epoch_1"]
        assert not policy_satisfied(p, attrs_bad)

    def test_empty_policy(self):
        assert not policy_satisfied("", ["anything"])

    def test_tokenize(self):
        tokens = _tokenize("role_Analyst and (clearance_2 or clearance_3)")
        assert "role_Analyst" in tokens
        assert "and" in tokens
        assert "(" in tokens
        assert "or" in tokens
        assert ")" in tokens

    def test_check_policy_returns_reason(self):
        ok, reason = check_policy("role_Analyst", ["role_Analyst"])
        assert ok
        assert "PASS" in reason

        ok, reason = check_policy("role_Analyst", ["role_Executor"])
        assert not ok
        assert "FAIL" in reason


