class TestCryptoPolicyIntegration:

    def test_full_policy_encrypt_decrypt(self):
        """End-to-end: policy generated from MemoryLabel, keys from AgentLabel."""
        topo = Topology()
        topo.add_agent("planner-1", parent=None)
        topo.add_agent("analyst-1", parent="planner-1")
        topo.add_agent("executor-1", parent="planner-1")

        engine = CryptoEngine(topo)

        # Register two agents with different attributes
        analyst = AgentLabel(agent_id="analyst-1", role=Role.ANALYST,
                             clearance=Clearance.L2_SENSITIVE,
                             trust_intrinsic=Trust.T2_MEDIUM,
                             task_domain={"incident-42"}, collab_group={"sec"},
                             epoch=1)
        executor = AgentLabel(agent_id="executor-1", role=Role.EXECUTOR,
                              clearance=Clearance.L1_INTERNAL,
                              trust_intrinsic=Trust.T1_LOW,
                              task_domain={"incident-99"}, collab_group={"ops"},
                              epoch=1)
        engine.register_agent(analyst)
        engine.register_agent(executor)

        # Memory created by planner, bound to incident-42
        mem = MemoryLabel(chunk_id="m-sec", sensitivity=Clearance.L2_SENSITIVE,
                          provenance_trust=Trust.T3_HIGH, layer=Layer.CONCLUSION,
                          memory_type=MemoryType.SEMANTIC, owner_agent="planner-1",
                          task_binding="incident-42", collab_group={"sec"},
                          epoch=1)

        ct = engine.encrypt_memory("security finding", mem)

        # Analyst (correct task, correct clearance, correct group) can decrypt
        plain, _ = engine.decrypt_memory(analyst, ct)
        assert plain is not None

        # Executor (wrong task, wrong group) cannot decrypt
        plain, reason = engine.decrypt_memory(executor, ct)
        assert plain is None
        assert "DENY" in reason

    def test_r_layer_restricts_to_ancestors(self):
        """R layer memory should only be decryptable by owner + ancestors + auditor."""
        topo = Topology()
        topo.add_agent("planner-1", parent=None)
        topo.add_agent("analyst-1", parent="planner-1")
        topo.add_agent("retriever-1", parent="planner-1")
        # analyst-2 is under analyst-1, so analyst-1 is its ancestor
        topo.add_agent("analyst-2", parent="analyst-1")

        engine = CryptoEngine(topo)

        planner = AgentLabel(agent_id="planner-1", role=Role.PLANNER,
                             clearance=Clearance.L3_SECRET,
                             trust_intrinsic=Trust.T3_HIGH,
                             task_domain={"task"}, epoch=1)
        # analyst-2: NOT an ancestor of planner-1
        analyst2 = AgentLabel(agent_id="analyst-2", role=Role.ANALYST,
                              clearance=Clearance.L2_SENSITIVE,
                              trust_intrinsic=Trust.T2_MEDIUM,
                              task_domain={"task"}, epoch=1)
        auditor = AgentLabel(agent_id="auditor-1", role=Role.AUDITOR,
                             clearance=Clearance.L3_SECRET,
                             trust_intrinsic=Trust.T3_HIGH,
                             task_domain={"task"}, epoch=1)

        engine.register_agent(planner)
        engine.register_agent(analyst2)
        engine.register_agent(auditor)

        # R-layer memory owned by planner-1
        mem = MemoryLabel(chunk_id="r1", sensitivity=Clearance.L2_SENSITIVE,
                          provenance_trust=Trust.T3_HIGH, layer=Layer.REASONING,
                          memory_type=MemoryType.TRAJECTORY, owner_agent="planner-1",
                          task_binding="task", epoch=1)

        ct = engine.encrypt_memory("planner reasoning chain", mem)

        # Planner (owner) can decrypt R-layer
        assert engine.decrypt_memory(planner, ct)[0] is not None

        # Auditor can decrypt R-layer (bypass)
        assert engine.decrypt_memory(auditor, ct)[0] is not None

        # analyst-2 (not an ancestor of planner-1) cannot decrypt
