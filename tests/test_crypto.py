class TestCKKS:

    @pytest.fixture
    def ctx(self):
        return ckks_setup()

    def test_encrypt_decrypt_roundtrip(self, ctx):
        vec = [1.0, 2.5, -3.0, 0.0, 100.0]
        enc = ckks_encode_encrypt(vec, ctx)
        dec = ckks_decrypt_decode(enc, ctx)
        for a, b in zip(vec, dec):
            assert math.isclose(a, b, rel_tol=1e-6)

    def test_add(self, ctx):
        a = ckks_encode_encrypt([1.0, 2.0, 3.0], ctx)
        b = ckks_encode_encrypt([4.0, 5.0, 6.0], ctx)
        enc_sum = ckks_add(a, b, ctx)
        dec = ckks_decrypt_decode(enc_sum, ctx)
        for x, y in zip(dec, [5.0, 7.0, 9.0]):
            assert math.isclose(x, y, rel_tol=1e-6)

    def test_sub(self, ctx):
        a = ckks_encode_encrypt([10.0, 8.0, 6.0], ctx)
        b = ckks_encode_encrypt([1.0, 2.0, 3.0], ctx)
        enc_sub = ckks_sub(a, b, ctx)
        dec = ckks_decrypt_decode(enc_sub, ctx)
        for x, y in zip(dec, [9.0, 6.0, 3.0]):
            assert math.isclose(x, y, rel_tol=1e-6)

    def test_multiply(self, ctx):
        a = ckks_encode_encrypt([2.0, 3.0, 4.0], ctx)
        b = ckks_encode_encrypt([5.0, 10.0, 0.5], ctx)
        enc_mul = ckks_multiply(a, b, ctx)
        dec = ckks_decrypt_decode(enc_mul, ctx)
        for x, y in zip(dec, [10.0, 30.0, 2.0]):
            assert math.isclose(x, y, rel_tol=1e-6)

    def test_inner_product(self, ctx):
        a = ckks_encode_encrypt([1.0, 2.0, 3.0], ctx)
        b = ckks_encode_encrypt([4.0, 5.0, 6.0], ctx)
        enc_ip = ckks_inner_product(a, b, ctx)
        dec = ckks_decrypt_decode(enc_ip, ctx)
        # 1*4 + 2*5 + 3*6 = 4+10+18 = 32
        assert math.isclose(dec[0], 32.0, rel_tol=1e-6)

    def test_scale(self, ctx):
        a = ckks_encode_encrypt([1.0, 2.0, 3.0], ctx)
        enc_scaled = ckks_scale(a, 3.0, ctx)
        dec = ckks_decrypt_decode(enc_scaled, ctx)
        for x, y in zip(dec, [3.0, 6.0, 9.0]):
            assert math.isclose(x, y, rel_tol=1e-6)

    def test_negate(self, ctx):
        a = ckks_encode_encrypt([1.0, -2.0, 3.0], ctx)
        enc_neg = ckks_negate(a, ctx)
        dec = ckks_decrypt_decode(enc_neg, ctx)
        for x, y in zip(dec, [-1.0, 2.0, -3.0]):
            assert math.isclose(x, y, rel_tol=1e-6)

    def test_square(self, ctx):
        a = ckks_encode_encrypt([1.0, 2.0, 3.0], ctx)
        enc_sq = ckks_square(a, ctx)
        dec = ckks_decrypt_decode(enc_sq, ctx)
        for x, y in zip(dec, [1.0, 4.0, 9.0]):
            assert math.isclose(x, y, rel_tol=1e-6)

    def test_sum(self, ctx):
        a = ckks_encode_encrypt([1.0, 2.0, 3.0, 4.0], ctx)
        enc_sum = ckks_sum(a, ctx)
        dec = ckks_decrypt_decode(enc_sum, ctx)
        assert math.isclose(dec[0], 10.0, rel_tol=1e-6)

    def test_power(self, ctx):
        a = ckks_encode_encrypt([1.0, 2.0, 3.0], ctx)
        enc_pow = ckks_power(a, 3, ctx)
        dec = ckks_decrypt_decode(enc_pow, ctx)
        for x, y in zip(dec, [1.0, 8.0, 27.0]):
            assert math.isclose(x, y, rel_tol=1e-6)

    def test_size_mismatch_raises(self, ctx):
        a = ckks_encode_encrypt([1.0, 2.0], ctx)
        b = ckks_encode_encrypt([1.0, 2.0, 3.0], ctx)
        with pytest.raises(ValueError):
            ckks_add(a, b, ctx)
        with pytest.raises(ValueError):
            ckks_inner_product(a, b, ctx)

    def test_context_mismatch_raises(self, ctx):
        ctx2 = ckks_setup()
        a = ckks_encode_encrypt([1.0, 2.0], ctx)
        b = ckks_encode_encrypt([1.0, 2.0], ctx2)
        with pytest.raises(ValueError):
            ckks_add(a, b, ctx)

    def test_different_encryptions_different_ciphertext(self, ctx):
        vec = [1.0, 2.0, 3.0]
        ct1 = ckks_encode_encrypt(vec, ctx)
        ct2 = ckks_encode_encrypt(vec, ctx)
        assert ct1._data != ct2._data  # probabilistic encryption

    def test_large_vector(self, ctx):
        vec = [float(i) for i in range(128)]
        enc = ckks_encode_encrypt(vec, ctx)
        dec = ckks_decrypt_decode(enc, ctx)
        for a, b in zip(vec, dec):
            assert math.isclose(a, b, rel_tol=1e-6)


